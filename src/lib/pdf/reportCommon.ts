// Shared header / footer / page-number helpers for report PDFs.
// Style = General Ledger PDF (landscape A4, navy, logo left, report name right).
import jsPDF from "jspdf"

export const NAVY    = [7, 8, 91]      as [number, number, number]
export const DARK    = [17, 24, 39]    as [number, number, number]
export const MUTED   = [107, 114, 128] as [number, number, number]
export const BORDER  = [229, 231, 235] as [number, number, number]
export const WHITE   = [255, 255, 255] as [number, number, number]
export const ROW_ALT = [248, 249, 252] as [number, number, number]

export const PW = 297
export const PH = 210
export const ML = 14
export const MR = 14

export interface CompanyHeaderInfo {
  companyName: string
  companyTagline?: string
  companyAddress?: string
  companyPhone?: string
  companyEmail?: string
  logoUrl?: string | null
}

export async function loadImage(url: string): Promise<string | null> {
  try {
    const res = await fetch(url)
    if (!res.ok) return null
    const blob = await res.blob()
    return await new Promise<string>(resolve => {
      const reader = new FileReader()
      reader.onload = () => resolve(reader.result as string)
      reader.onerror = () => resolve("")
      reader.readAsDataURL(blob)
    })
  } catch {
    return null
  }
}

// Reads address / phone / email saved in Settings > Company.
// Never throws: if nothing can be read, the three lines are simply left out.
export async function fetchCompanyContact(
  supabase: any,
  companyId: string
): Promise<{ companyAddress: string; companyPhone: string; companyEmail: string }> {
  const blank = { companyAddress: "", companyPhone: "", companyEmail: "" }
  if (!companyId) return blank
  try {
    const { data } = await supabase
      .from("company_settings")
      .select("address, phone, email")
      .eq("company_id", companyId)
      .maybeSingle()
    if (!data) return blank
    return {
      companyAddress: data.address || "",
      companyPhone: data.phone || "",
      companyEmail: data.email || "",
    }
  } catch {
    return blank
  }
}

// Draws the standard header. Returns the Y position where the table should start.
export async function drawReportHeader(
  doc: jsPDF,
  info: CompanyHeaderInfo,
  title: string,
  subtitleLines: string[]
): Promise<number> {
  const LOGO_SIZE = 20, LOGO_X = ML, LOGO_Y = 7

  let logoData: string | null = null
  if (info.logoUrl) logoData = await loadImage(info.logoUrl)
  if (logoData) doc.addImage(logoData, "PNG", LOGO_X, LOGO_Y, LOGO_SIZE, LOGO_SIZE)

  const textX = logoData ? LOGO_X + LOGO_SIZE + 5 : ML
  doc.setTextColor(...NAVY)
  doc.setFont("helvetica", "bold")
  doc.setFontSize(14)
  doc.text(info.companyName || "", textX, LOGO_Y + 7)

  doc.setFont("helvetica", "normal")
  doc.setFontSize(8.5)
  doc.setTextColor(...MUTED)
  doc.text(info.companyTagline || "", textX, LOGO_Y + 13)

  let infoY = LOGO_Y + 19
  let lastY = LOGO_Y + 13
  if (info.companyAddress) { doc.text(info.companyAddress, textX, infoY); lastY = infoY; infoY += 4 }
  if (info.companyPhone)   { doc.text("Phone: " + info.companyPhone, textX, infoY); lastY = infoY; infoY += 4 }
  if (info.companyEmail)   { doc.text("Email: " + info.companyEmail, textX, infoY); lastY = infoY; infoY += 4 }

  // Report name (right)
  doc.setFont("helvetica", "bold")
  doc.setFontSize(24)
  doc.setTextColor(...NAVY)
  doc.text(title, PW - MR, LOGO_Y + 8, { align: "right" })

  doc.setFont("helvetica", "normal")
  doc.setFontSize(8.5)
  doc.setTextColor(...MUTED)
  let subY = LOGO_Y + 16
  subtitleLines.filter(Boolean).forEach(line => {
    doc.text(line, PW - MR, subY, { align: "right" })
    lastY = Math.max(lastY, subY)
    subY += 5
  })

  // Divider sits below the logo AND below the last text line (so nothing overlaps it)
  const HEADER_BOTTOM = Math.max(LOGO_Y + LOGO_SIZE + 5, lastY + 3)
  doc.setDrawColor(...NAVY)
  doc.setLineWidth(0.6)
  doc.line(ML, HEADER_BOTTOM, PW - MR, HEADER_BOTTOM)
  return HEADER_BOTTOM + 6
}

// Footer line + "Generated by ..." + "Page X of Y" on every page. Call after the table(s).
export function addFooterAndPageNumbers(doc: jsPDF, companyName: string, companyTagline?: string) {
  const total = doc.getNumberOfPages()
  for (let i = 1; i <= total; i++) {
    doc.setPage(i)
    doc.setDrawColor(...NAVY)
    doc.setLineWidth(0.4)
    doc.line(ML, PH - 14, PW - MR, PH - 14)
    doc.setFont("helvetica", "normal")
    doc.setFontSize(7.5)
    doc.setTextColor(...MUTED)
    const tag = companyTagline ? `  \u00B7  ${companyTagline}` : ""
    doc.text(`Generated by ${companyName || "OneAccounts"}${tag}`, PW / 2, PH - 8, { align: "center" })
    doc.text(`Page ${i} of ${total}`, PW - MR, PH - 8, { align: "right" })
  }
}
